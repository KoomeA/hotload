def test_live_filter_rules():
    normal = engine._duration_filter(60, None, None)
    assert "Record live stream" in normal({"is_live": True}, incomplete=False)  # tells the user what to do instead
    rec = engine._duration_filter(60, None, None, recording=True)
    assert rec({"is_live": True, "duration": None}, incomplete=False) is None
    assert rec({"is_live": True, "live_status": "is_upcoming"}, incomplete=False) == "This stream has not started yet"
    assert rec({"is_live": True, "duration": 99999}, incomplete=False) is None  # media length does not apply; -t does
    assert engine.summarise({"live_status": "is_live", "is_live": True})["live_status"] == "is_live"


