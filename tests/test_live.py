def live_stream(tmp_path):
    """A real, endless HLS live stream generated by FFmpeg and served over HTTP on localhost."""
    d = tmp_path / "live"
    d.mkdir()
    ff = subprocess.Popen(
        ["ffmpeg", "-loglevel", "error", "-re", "-f", "lavfi", "-i", "testsrc=s=160x120:r=10", "-f", "lavfi", "-i", "sine=frequency=440",
         "-c:v", "libx264", "-preset", "ultrafast", "-pix_fmt", "yuv420p", "-g", "20", "-c:a", "aac", "-f", "hls", "-hls_time", "2",
         "-hls_list_size", "6", "-hls_flags", "delete_segments+omit_endlist", str(d / "live.m3u8")],
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    srv = http.server.ThreadingHTTPServer(("127.0.0.1", 0), functools.partial(http.server.SimpleHTTPRequestHandler, directory=str(d)))
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    deadline = time.time() + 20
    while time.time() < deadline and len(list(d.glob("*.ts"))) < 3:
        time.sleep(0.3)
    yield f"http://127.0.0.1:{srv.server_port}/live.m3u8", ff
    ff.kill()
    ff.wait()
    srv.shutdown()


@needs_ffmpeg
def test_records_a_real_live_stream_and_stops_by_itself(live_stream, tmp_path):
    url, ffmpeg = live_stream
    r = engine.download(url, Settings(allow_private_targets=True), tmp_path / "out", engine.PRESETS["best_mp4"], live_seconds=5)
    assert ffmpeg.poll() is None, "the stream is still live: the recording ended because of the cap, not the stream"
    secs = float(subprocess.check_output(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(r.path)]))
    assert 4.0 <= secs <= 6.5 and r.path.suffix == ".mp4" and r.path.stat().st_size > 10_000


