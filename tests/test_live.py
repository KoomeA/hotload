def job(c, **kw):
    return c.post("/api/v1/jobs", json={"url": "https://example.com/live", "live_minutes": 10, **kw})


def stored(c, job_id):
    return c.portal.call(c.app.state.store.get, job_id)


def test_self_host_cap_and_validation(make):
    c = make(max_live_minutes=30)
    ok = job(c)
    assert ok.status_code == 202 and stored(c, ok.json()["id"]).live_seconds == 600
    assert job(c, live_minutes=31).status_code == 400 and "30 minutes" in job(c, live_minutes=31).json()["detail"]
    for bad in (0, -5, 241):
        assert job(c, live_minutes=bad).status_code == 422
    assert job(c, start=1, end=5).status_code == 422 and job(c, sponsorblock="mark").status_code == 422
    assert job(c, preset="subtitles", subtitle_langs=["en"]).status_code == 400
    assert c.post("/api/v1/jobs", json={"url": "https://example.com/v"}).status_code == 202  # not a recording
    assert stored(c, c.post("/api/v1/jobs", json={"url": "https://example.com/v"}).json()["id"]).live_seconds is None


def test_recording_is_a_paid_feature_with_plan_caps_when_enforced(make):
    c = make(quotas_enabled=True, egress_filtered=True)
    assert job(c).status_code == 403  # anonymous
    c.post("/api/v1/auth/register", json={"email": "r@example.com", "password": "correct horse battery"})
    uid = c.get("/api/v1/me").json()["id"]
    assert job(c).status_code == 403 and "Premium" in job(c).json()["detail"]  # free
    db = c.app.state.db
    c.portal.call(db.set_tier, uid, "premium", time.time() + 86400)
    assert job(c, live_minutes=30).status_code == 202 and job(c, live_minutes=31).status_code == 400
    c.portal.call(db.set_tier, uid, "pro", time.time() + 86400)
    assert job(c, live_minutes=60).status_code == 202 and job(c, live_minutes=61).status_code == 400


# --- worker progress ------------------------------------------------------------------------------

async def test_recording_progress_is_reported_by_elapsed_time(monkeypatch):
    store = JobStore(FakeAsyncRedis(decode_responses=True), 600)
    j = await store.create(url="https://example.com/live", preset="best_mp4", live_seconds=10)
    real_sleep = asyncio.sleep

    async def fast(_):
        await real_sleep(0.01)

    monkeypatch.setattr(worker.asyncio, "sleep", fast)
    task = asyncio.create_task(worker._report_recording(store, j, 10))
    await real_sleep(0.1)
    task.cancel()
    saved = await store.get(j.id)
    assert saved.message.startswith("Recording") and "of 10s" in saved.message and 0 <= saved.progress <= 99.0
